"""Build the URL-to-local-provenance index used by PUBLIC_SOURCES.md."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "PUBLIC_SOURCES.md"
URL_RE = re.compile(r"https?://[^\s<>()\[\]{}\"'`]+")
TEXT_SUFFIXES = {".md", ".py", ".json", ".txt", ".cff", ".yml", ".yaml"}
TRAILING = ",.;:'\"`"


def clean_url(raw: str) -> str:
    url = raw.rstrip(TRAILING)
    while url.endswith(")") and url.count(")") > url.count("("):
        url = url[:-1]
    return url


def main() -> None:
    found: dict[str, set[str]] = {}
    for path in ROOT.rglob("*"):
        if not path.is_file() or ".git" in path.parts or path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for match in URL_RE.findall(text):
            url = clean_url(match)
            if url:
                found.setdefault(url, set()).add(path.relative_to(ROOT).as_posix())

    lines = [
        "# Public source index",
        "",
        "This file is generated by `build_public_source_index.py`. It records every",
        "public URL found in the repository's source, reports, and saved metadata,",
        "along with the local files that cite or preserve it. The curated primary",
        "sources and citation rules are in [`CITATIONS.md`](CITATIONS.md).",
        "",
        f"Indexed URLs: **{len(found)}**.",
        "",
        "| URL | Local provenance |",
        "| --- | --- |",
    ]
    for url in sorted(found):
        provenance = ", ".join(f"`{item}`" for item in sorted(found[url]))
        lines.append(f"| <{url}> | {provenance} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"indexed {len(found)} URLs into {OUT.name}")


if __name__ == "__main__":
    main()
