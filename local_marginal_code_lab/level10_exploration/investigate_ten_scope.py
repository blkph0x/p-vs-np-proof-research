"""Add an actual ten-coordinate table to the selected mixed-incidence model.

The scope is the original rank-six Bonferroni control. Every nonempty subset
whose affine span has at most eight points is tied to the corresponding base
moment, including closures outside this scope. Moment transport uses an
explicit injective linear coordinate map on each small span. The actual
pinned quadratic projection is generated by its linear/quadratic evaluation
rows, rather than assumed from the absence of obvious checks.
"""
from collections import Counter
from fractions import Fraction
from itertools import combinations
from pathlib import Path
import argparse
import hashlib
import json
import time

import investigate_mixed_cut as mixed

HERE = Path(__file__).resolve().parent
SCOPE = (1, 2, 4, 8, 12, 16, 20, 24, 28, 32)


def affine_closure(points):
    origin = min(points)
    direction = {0}
    for point in points:
        direction |= {value ^ point ^ origin for value in tuple(direction)}
    return tuple(sorted(origin ^ value for value in direction))


def linear_image(points):
    """Explicit injective coordinates for the linear span of supplied points."""
    basis = {}
    for point in sorted(points):
        residual = point
        for pivot, vector in sorted(basis.items(), reverse=True):
            if residual >> pivot & 1:
                residual ^= vector
        if residual:
            basis[residual.bit_length() - 1] = residual
    ordered = sorted(basis.items(), reverse=True)
    images = []
    for point in points:
        residual, code = point, 0
        for index, (pivot, vector) in enumerate(ordered):
            if residual >> pivot & 1:
                residual ^= vector
                code ^= 1 << index
        if residual:
            raise ValueError("failed span encoding")
        images.append(code)
    return tuple(images), [vector for _, vector in ordered]


def projection_atoms(scope):
    rows = [sum(((point >> bit) & 1) << i for i, point in enumerate(scope))
            for bit in range(6)]
    rows += [sum((((point >> a) & (point >> b)) & 1) << i
                 for i, point in enumerate(scope)) for a, b in combinations(range(6), 2)]
    span = {0}
    for row in rows:
        span |= {value ^ row for value in tuple(span)}
    return sorted(value ^ ((1 << len(scope)) - 1) for value in span), rows


def build():
    model, metadata = mixed.make_model(True)
    model["name"] = "rm2_mixed_nine_plus_ten_scope"
    atoms, generators = projection_atoms(SCOPE)
    start = len(model["objective"])
    model["objective"].extend(["0"] * len(atoms))
    model["variable_ids"] = [f"x{i:06d}" for i in range(len(model["objective"]))]
    model["rows"].append({str(start + i): "1" for i in range(len(atoms))})
    model["rhs"].append("1")
    moment_rows = []
    for mask in range(1, 1 << len(SCOPE)):
        points = tuple(point for i, point in enumerate(SCOPE) if mask >> i & 1)
        closure = affine_closure(points)
        if len(closure) > 8:
            continue
        encoded, basis = linear_image(points)
        if len(basis) > 4:
            raise ValueError("small affine span has unexpectedly large linear rank")
        moment = mixed.geometry.base_moment(encoded)
        row = Counter({start + i: 1 for i, atom in enumerate(atoms) if atom & mask == mask})
        for col, count in moment["coefficients"].items():
            row[col] -= count
        moment_rows.append({
            "mask": mask, "points": list(points), "closure": list(closure),
            "encoded_points": list(encoded), "linear_basis": basis,
            "moment": moment, "row_index": len(model["rows"]),
        })
        model["rows"].append({str(col): str(count) for col, count in row.items() if count})
        model["rhs"].append("0")
    model["row_ids"] = [f"r{i:06d}" for i in range(len(model["rows"]))]
    mixed.model_digest(model)
    metadata.update({
        "scope": list(SCOPE), "allowed_atoms": atoms, "projection_generators": generators,
        "first_scope_column": start, "moment_rows": moment_rows,
        "scope_statement": "One selected ten-point table plus necessary mixed-incidence conditions.",
    })
    return model, metadata


def genuine_d6_point(model, metadata):
    """Actual uniform codimension-two subspace indicators in GF(2)^6."""
    kernels = set()
    for a, b in combinations(range(1, 64), 2):
        kernels.add(sum(1 << point for point in range(64)
                        if (a & point).bit_count() % 2 == 0
                        and (b & point).bit_count() % 2 == 0))
    denominator = len(kernels)
    allowed, var_for, _, _, _ = mixed.geometry._base()
    representative = {}
    for key, orbit in var_for.items():
        representative.setdefault(orbit, key)

    def pattern(kernel, scope):
        return sum(((kernel >> point) & 1) << i for i, point in enumerate(scope))

    primal = [Fraction(sum(pattern(kernel, scope) == atom for kernel in kernels), denominator)
              for scope, atom in (representative[i] for i in range(28))]
    flat, outside = tuple(range(16, 24)), 24
    b = []
    for orbit in range(5, 11):
        atom = next(atom for atom in allowed[flat] if var_for[(flat, atom)] == orbit)
        b.append(Fraction(sum(pattern(kernel, flat) == atom and (kernel >> outside) & 1
                              for kernel in kernels), denominator))
    primal.extend(b)
    primal.extend(primal[5 + i] - b[i] for i in range(6))
    cut_row = model["rows"][64]
    primal.append(sum(Fraction(coefficient) * primal[int(column)]
                      for column, coefficient in cut_row.items() if int(column) < 40))
    scope_counts = Counter(pattern(kernel, SCOPE) for kernel in kernels)
    primal.extend(Fraction(scope_counts[atom], denominator) for atom in metadata["allowed_atoms"])
    if len(primal) != len(model["objective"]) or any(value < 0 for value in primal):
        raise ValueError("D6 primal dimensions/nonnegativity")
    residuals = [sum(Fraction(coefficient) * primal[int(col)] for col, coefficient in row.items())
                 - Fraction(target) for row, target in zip(model["rows"], model["rhs"])]
    if any(residuals):
        raise ValueError("D6 actual global distribution fails a selected row")
    value = sum(Fraction(c) * x for c, x in zip(model["objective"], primal))
    return {"status": "EXACT_FEASIBLE_POINT", "kernel_count": denominator,
            "singleton_probability": str(value), "primal": list(map(str, primal)),
            "checked_rows": len(residuals), "all_residuals_zero": True,
            "scope": "Actual GF(2)^6 global codeword distribution; not a generic higher-dimensional extension."}


def source_hashes():
    result = mixed.hashes()
    result["level10_exploration/investigate_ten_scope.py"] = hashlib.sha256(
        Path(__file__).read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--soplex", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--timeout", type=int, default=120)
    args = parser.parse_args()
    out = args.output_dir.resolve()
    if out.exists() and any(out.iterdir()):
        raise ValueError("output directory must be new or empty")
    out.mkdir(parents=True, exist_ok=True)
    before = source_hashes()
    started = time.perf_counter()
    model, metadata = build()
    control = genuine_d6_point(model, metadata)
    mixed.write_json(out / "d6-feasible-control.json", control)
    result = mixed.solve(args.soplex, out / "selected_ten_scope", model, metadata, args.timeout)
    after = source_hashes()
    report = {
        "schema": "rm2-level10-selected-scope-exploration-v1",
        "status": "EXACT_SELECTED_MODEL" if before == after else "UNKNOWN",
        "source_sha256_lf": before, "source_after_sha256_lf": after,
        "sources_unchanged": before == after, "selected_result": result,
        "d6_control_probability": control["singleton_probability"],
        "solver_sha256": hashlib.sha256(args.soplex.read_bytes()).hexdigest(),
        "elapsed_seconds": time.perf_counter() - started,
        "full_L10_optimum": "NOT_DETERMINED_BY_SELECTED_MODEL_FEASIBILITY",
    }
    mixed.write_json(out / "RESULTS.json", report)
    print(json.dumps({key: report[key] for key in ("status", "sources_unchanged",
                     "d6_control_probability", "elapsed_seconds", "full_L10_optimum")}))
    print(json.dumps({key: result[key] for key in ("singleton_optimum", "rows",
                     "variables", "nonzeros", "solver_seconds")}))
    return 0 if before == after else 2


if __name__ == "__main__":
    raise SystemExit(main())
